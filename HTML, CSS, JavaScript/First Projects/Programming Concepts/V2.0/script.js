// Navegación por letras (concept.html)
// Al hacer clic en una letra se muestran solo los conceptos de esa letra

function mostrarConceptosDeLetra(letra) {
    const GRUPOS = document.querySelectorAll(".grupo-letra");
    const BOTONES = document.querySelectorAll(".btn-letra");
    const BARRA = document.querySelector(".abecedario");
    const SIN_ANIMACION = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
    const COMPORTAMIENTO = SIN_ANIMACION ? "auto" : "smooth";

    GRUPOS.forEach(function (grupo) {
        grupo.classList.toggle("activo", grupo.dataset.letra === letra);
    });

    BOTONES.forEach(function (boton) {
        const ES_ACTIVO = boton.dataset.letra === letra;
        boton.classList.toggle("activo", ES_ACTIVO);
        boton.setAttribute("aria-pressed", ES_ACTIVO);

        // En celulares la barra se desliza: centra la letra elegida
        if (ES_ACTIVO) {
            boton.scrollIntoView({ inline: "center", block: "nearest", behavior: COMPORTAMIENTO });
        }
    });

    // Si ya habías bajado en la página, sube al inicio de los conceptos de la nueva letra
    const GRUPO_ACTIVO = document.querySelector(".grupo-letra.activo");
    if (GRUPO_ACTIVO && BARRA) {
        const MARGEN = BARRA.offsetHeight + 12;
        const DISTANCIA = GRUPO_ACTIVO.getBoundingClientRect().top - MARGEN;
        if (DISTANCIA < 0) {
            window.scrollTo({ top: window.scrollY + DISTANCIA, behavior: COMPORTAMIENTO });
        }
    }
}

document.querySelectorAll(".btn-letra").forEach(function (boton) {
    boton.addEventListener("click", function () {
        mostrarConceptosDeLetra(boton.dataset.letra);
    });
});